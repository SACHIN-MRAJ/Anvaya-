r"""Writes the API contract and the PostgreSQL schema straight from the code, so they never drift.

Run from backend/:  .venv\Scripts\python scripts\export_contract.py
Outputs:  ../documents/backend/openapi.yaml   (OpenAPI 3.1: every route the app serves, errors as Problem Details)
          ../documents/backend/schema.sql     (exactly what `alembic upgrade head` runs on PostgreSQL: tables, the
                                          least-privilege role, row-level-security policies, append-only log)
"""
import os
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
os.environ.setdefault("ANUMATI_SCHEDULER_ENABLED", "false")

from app.db import Base  # noqa: E402
from app.main import app  # noqa: E402

OUT = ROOT.parent / "documents" / "backend"
OUT.mkdir(parents=True, exist_ok=True)

spec = app.openapi()
class _NoAliases(yaml.SafeDumper):
    def ignore_aliases(self, data) -> bool:
        return True


(OUT / "openapi.yaml").write_text(yaml.dump(spec, Dumper=_NoAliases, sort_keys=False, allow_unicode=True, width=120), encoding="utf-8")

# Alembic's offline mode prints the SQL instead of running it; no database is needed.
env = {k: v for k, v in os.environ.items() if not k.startswith("ANUMATI_DATABASE")}
env["ANUMATI_DATABASE_URL"] = "postgresql+asyncpg://anumati@localhost/anumati"
sql = subprocess.run([sys.executable, "-m", "alembic", "upgrade", "head", "--sql"], cwd=ROOT, env=env, capture_output=True, text=True, check=True).stdout
header = (
    "-- ANUMATI database schema for PostgreSQL 16, as applied by `alembic upgrade head` (generated by scripts/export_contract.py).\n"
    f"-- {len(Base.metadata.sorted_tables)} tables, the anumati_app runtime role, row-level security and an append-only evidence log.\n"
    "-- Development uses the same models on SQLite.\n\n"
)
(OUT / "schema.sql").write_text(header + sql, encoding="utf-8")

ops = sum(1 for p in spec["paths"].values() for m in p if m in {"get", "post", "put", "delete", "patch"})
print(f"openapi.yaml: {len(spec['paths'])} paths, {ops} operations")
print(f"schema.sql: {len(Base.metadata.sorted_tables)} tables, {sql.count('CREATE POLICY')} row-security policies")
